ON CONFLICT (id) DO NOTHING;

-- 2. Tabla de Contactos & Resúmenes por Número y {name}
CREATE TABLE IF NOT EXISTS public.growfit_whatsapp_contacts (
    phone TEXT PRIMARY KEY,
    name TEXT NOT NULL DEFAULT 'Contacto WhatsApp',
    circle TEXT NOT NULL DEFAULT 'otros', -- 'hijos' | 'novia' | 'trabajo' | 'amigos' | 'otros'
    is_important BOOLEAN DEFAULT FALSE,
    short_summary TEXT,
    detailed_analysis TEXT,
    pending_promises JSONB DEFAULT '[]'::jsonb,
    detected_calendar_events JSONB DEFAULT '[]'::jsonb,
    smart_replies JSONB DEFAULT '[]'::jsonb,
    last_message_preview TEXT,
    last_message_at TIMESTAMPTZ DEFAULT NOW(),
    total_messages INTEGER DEFAULT 0,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

ALTER TABLE public.growfit_whatsapp_contacts ADD COLUMN IF NOT EXISTS pending_promises JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.growfit_whatsapp_contacts ADD COLUMN IF NOT EXISTS detected_calendar_events JSONB DEFAULT '[]'::jsonb;
ALTER TABLE public.growfit_whatsapp_contacts ADD COLUMN IF NOT EXISTS smart_replies JSONB DEFAULT '[]'::jsonb;

-- 3. Tabla de Mensajes (message.incoming, message.outgoing, message.calling)
CREATE TABLE IF NOT EXISTS public.growfit_whatsapp_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone TEXT NOT NULL,
    contact_name TEXT NOT NULL DEFAULT 'Contacto',
    direction TEXT NOT NULL DEFAULT 'incoming', -- 'incoming' | 'outgoing' | 'call'
    event_name TEXT NOT NULL DEFAULT 'message.incoming',
    body TEXT,
    media_url TEXT,
    ai_voice TEXT,
    ai_image TEXT,
    ai_response TEXT,
    circle TEXT DEFAULT 'otros',
    is_important BOOLEAN DEFAULT FALSE,
    detected_event JSONB,
    project_id TEXT,
    raw_payload JSONB,
    message_date DATE DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_gf_wa_messages_phone ON public.growfit_whatsapp_messages(phone);
CREATE INDEX IF NOT EXISTS idx_gf_wa_messages_date ON public.growfit_whatsapp_messages(message_date);
CREATE INDEX IF NOT EXISTS idx_gf_wa_messages_circle ON public.growfit_whatsapp_messages(circle);

ALTER TABLE public.growfit_bot_status ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.growfit_whatsapp_contacts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.growfit_whatsapp_messages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow all access to growfit_bot_status" ON public.growfit_bot_status;
CREATE POLICY "Allow all access to growfit_bot_status" ON public.growfit_bot_status FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all access to growfit_whatsapp_contacts" ON public.growfit_whatsapp_contacts;
CREATE POLICY "Allow all access to growfit_whatsapp_contacts" ON public.growfit_whatsapp_contacts FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow all access to growfit_whatsapp_messages" ON public.growfit_whatsapp_messages;
CREATE POLICY "Allow all access to growfit_whatsapp_messages" ON public.growfit_whatsapp_messages FOR ALL USING (true) WITH CHECK (true);

GRANT ALL ON TABLE public.growfit_bot_status TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.growfit_whatsapp_contacts TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.growfit_whatsapp_messages TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

