-- 1. Tabla de Estado del Bot (status.online, status.require_action, status.disconnect)
CREATE TABLE IF NOT EXISTS public.growfit_bot_status (
    id TEXT PRIMARY KEY DEFAULT 'builderbot_main',
    bot_id TEXT DEFAULT 'f7806984-3538-457b-b4a3-84c97293583b',
    status TEXT NOT NULL DEFAULT 'online',
    qr_code TEXT,
    reason TEXT,
    last_event TEXT,
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

